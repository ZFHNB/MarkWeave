const EMOJI_PATTERN = /:([a-z0-9_+\-]+):/g;

export function replaceEmojiShortcodes(text: string): string {
  return text.replace(EMOJI_PATTERN, (match, name: string) => {
    const emoji = EMOJI_MAP[name];
    return emoji ?? match;
  });
}

/** 在 DOM 树中把文本节点里的 emoji 短代码替换为实际字符（跳过 code/pre）。 */
export function applyEmojiToDom(root: HTMLElement): void {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, {
    acceptNode(node) {
      const parent = (node as Text).parentElement;
      if (!parent) return NodeFilter.FILTER_REJECT;
      const tag = parent.tagName.toLowerCase();
      if (tag === "code" || tag === "pre") return NodeFilter.FILTER_REJECT;
      return NodeFilter.FILTER_ACCEPT;
    },
  });

  const targets: Text[] = [];
  let current = walker.nextNode();
  while (current) {
    targets.push(current as Text);
    current = walker.nextNode();
  }

  for (const node of targets) {
    const replaced = replaceEmojiShortcodes(node.nodeValue || "");
    if (replaced !== node.nodeValue) node.nodeValue = replaced;
  }
}
